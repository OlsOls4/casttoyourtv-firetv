#!/usr/bin/env bash
# Scaffold the Vega app from the official helloWorld template (unless app/ is committed),
# overlay our sources from app-src/, add dependencies + media privileges, write the
# build-time config, and build the release vpkg. Writes $OUT/vpkg-path.txt.
set -euo pipefail
export PATH="$HOME/vega/bin:$PATH"
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
APP_DIR=${APP_DIR:-$ROOT/app}
APP_NAME=${APP_NAME:-CastToYourTV}
PACKAGE_ID=${PACKAGE_ID:-com.olsols4.casttoyourtv}
OUT=${OUT:-$ROOT/artifacts}; mkdir -p "$OUT/logs"

if [[ ! -f "$APP_DIR/package.json" ]]; then
  echo "::group::vega project generate (helloWorld)"
  vega project generate --template helloWorld --name "$APP_NAME" --packageId "$PACKAGE_ID" --outputDir "$APP_DIR"
  echo "::endgroup::"
  # keep a pristine copy of the scaffold for reference
  tar --exclude=node_modules -czf "$OUT/template-scaffold.tgz" -C "$(dirname "$APP_DIR")" "$(basename "$APP_DIR")"
fi
( cd "$APP_DIR" && find . -path ./node_modules -prune -o -type f -print | sort ) > "$OUT/logs/scaffold-files.txt"
cp "$APP_DIR/manifest.toml" "$OUT/logs/manifest.template.toml" 2>/dev/null || true
cp "$APP_DIR/package.json" "$OUT/logs/package.template.json" 2>/dev/null || true
cat "$APP_DIR/src/App.tsx" > "$OUT/logs/App.template.tsx" 2>/dev/null || true

echo "::group::overlay app-src"
cp -rv "$ROOT/app-src/." "$APP_DIR/"
cat > "$APP_DIR/src/ct/buildConfig.ts" <<CFG
// generated by ci/scripts/prepare-app.sh
export const BUILD = {
  pairCode: '${PAIR_CODE:-}',
  offlineAsk: ${OFFLINE_ASK:-false},
  label: '${BUILD_LABEL:-ci}',
};
CFG
node - "$APP_DIR" <<'JS'
const fs = require('fs'); const path = require('path');
const dir = process.argv[2];
const pj = path.join(dir, 'package.json');
const p = JSON.parse(fs.readFileSync(pj, 'utf8'));
p.dependencies = Object.assign({}, p.dependencies, {
  '@amazon-devices/react-native-w3cmedia': '~2.3.2',
  'qrcode-generator': '^1.4.4',
});
fs.writeFileSync(pj, JSON.stringify(p, null, 2) + '\n');
// manifest: title + media/network privileges (appended as array-of-tables, deduped)
const mf = path.join(dir, 'manifest.toml');
let m = fs.readFileSync(mf, 'utf8');
m = m.replace(/^title\s*=.*$/m, 'title = "Cast to Your TV"');
const wants = [
  ['service', 'com.amazon.mediametrics.service'], ['service', 'com.amazon.media.server'],
  ['service', 'com.amazon.gipc.uuid.*'], ['service', 'com.amazon.media.playersession.service'],
  ['privilege', 'com.amazon.devconf.privilege.accessibility'], ['service', 'com.amazon.mediabuffer.service'],
  ['service', 'com.amazon.mediatransform.service'], ['service', 'com.amazon.audio.stream'],
  ['service', 'com.amazon.audio.control'], ['service', 'com.amazon.network.service'],
  ['service', 'com.amazon.inputd.service'],
];
let add = '\n# --- added by casttoyourtv prepare-app.sh: W3C media + input + network ---\n';
for (const [kind, id] of wants) if (!m.includes(`"${id}"`)) add += `[[wants.${kind}]]\nid = "${id}"\n\n`;
if (!/\[\[offers\.service\]\][^\[]*com\.amazon\.gipc\.uuid/.test(m)) add += `[[offers.service]]\nid = "com.amazon.gipc.uuid.*"\n`;
fs.writeFileSync(mf, m + add);
JS
cp "$APP_DIR/manifest.toml" "$OUT/logs/manifest.final.toml"
echo "::endgroup::"

cd "$APP_DIR"
echo "::group::npm install"
npm install --no-audit --no-fund
echo "::endgroup::"
echo "::group::build:release"
npm run build:release
echo "::endgroup::"
find build -name '*.vpkg' -exec ls -la {} \; | tee "$OUT/logs/vpkgs.txt"
VPKG=$(find "$PWD/build" -name '*x86_64*.vpkg' | grep -i release | head -1)
[[ -z "$VPKG" ]] && VPKG=$(find "$PWD/build" -name '*x86_64*.vpkg' | head -1)
[[ -z "$VPKG" ]] && { echo "no x86_64 vpkg built"; exit 1; }
echo "$VPKG" > "$OUT/vpkg-path.txt"
cp "$VPKG" "$OUT/"
echo "built $VPKG"
