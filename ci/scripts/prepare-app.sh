#!/usr/bin/env bash
# Build the Vega app in app/ (generated from the official helloWorld template, then
# customised). Writes the build-time config, runs unit tests, builds the release vpkg
# and writes its path to $OUT/vpkg-path.txt.
#   PAIR_CODE   fixed pairing code baked into the build (CI demo); empty = random per launch
#   OFFLINE_ASK true = deterministic offline answers only
set -euo pipefail
export PATH="$HOME/vega/bin:$PATH"
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
APP_DIR=${APP_DIR:-$ROOT/app}
OUT=${OUT:-$ROOT/artifacts}; mkdir -p "$OUT/logs"

cat > "$APP_DIR/src/ct/buildConfig.ts" <<CFG
// generated by ci/scripts/prepare-app.sh
export const BUILD = {
  pairCode: '${PAIR_CODE:-}',
  offlineAsk: ${OFFLINE_ASK:-false},
  label: '${BUILD_LABEL:-local}',
};
CFG

cd "$APP_DIR"
echo "::group::npm install"
npm install --no-audit --no-fund
echo "::endgroup::"
echo "::group::unit tests"
npx jest --ci 2>&1 | tee "$OUT/logs/unit-tests.log" || echo "::warning::unit tests failed (see logs/unit-tests.log)"
echo "::endgroup::"
echo "::group::build:release"
npm run build:release
echo "::endgroup::"
find build -name '*.vpkg' -exec ls -la {} \; | tee "$OUT/logs/vpkgs.txt"
VPKG=$(find "$PWD/build" -name '*x86_64*.vpkg' | grep -i release | head -1)
[[ -z "$VPKG" ]] && VPKG=$(find "$PWD/build" -name '*x86_64*.vpkg' | head -1)
[[ -z "$VPKG" ]] && { echo "no x86_64 vpkg built"; exit 1; }
echo "$VPKG" > "$OUT/vpkg-path.txt"
cp "$VPKG" "$OUT/"
echo "built $VPKG"
